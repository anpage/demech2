#!/usr/bin/env python3
"""The targets manifest (targets.toml): the documents generated from it, and the check that the
places that still list the targets by hand agree with it.

targets.toml is the one place a target is declared. From it this writes docs/TARGETS.md (the
targets, their originals, their build configuration, their game-code totals, a reccmp-user.yml
to start from) and the README's status table, between its markers. --check fails when either is
stale, and when reccmp-project.yml (the targets, their order, file names, hashes and source roots)
or verify-retail.yml's RETAIL_ENTRIES and hashes say something else (build.yml's lists come from
--list and --sources).

Other tools read the manifest through load(): it is TOML, which Python's standard library reads,
so they need nothing installed for it (--check reads reccmp-project.yml with reccmp's YAML library).

usage (from anywhere):
  python tools/targets.py --doc      rewrite docs/TARGETS.md and the README's table
  python tools/targets.py --check    what CI runs
  python tools/targets.py --list [--availability public|retail] [--format ids|totals|entries]
  python tools/targets.py --sources TARGET     its source directories, for decomplint
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "targets.toml"
DOC = ROOT / "docs" / "TARGETS.md"
README = ROOT / "README.md"
PAGES = "https://anpage.github.io/demech2"

REQUIRED = ("binary", "component", "edition", "short", "what", "about", "sha256", "size", "linked", "availability",
            "origin", "sources", "compiler", "language", "cl", "crt", "link", "built-in", "output", "total",
            "game-code", "macros")
COMPONENTS = ("launcher", "shell", "simulator", "lobby")
BEGIN = "<!-- targets:%s begin (generated by tools/targets.py --doc from targets.toml) -->"
END = "<!-- targets:%s end -->"


def load_yaml(path):
    """reccmp-project.yml, for --check (reccmp's own YAML library, or PyYAML)."""
    text = Path(path).read_text(encoding="utf-8")
    try:
        from ruamel.yaml import YAML
        return YAML(typ="safe").load(text)
    except ImportError:
        import yaml
        return yaml.safe_load(text)


def load():
    """The targets, in the manifest's order: {id: {field: value}}."""
    with open(MANIFEST, "rb") as file:
        targets = tomllib.load(file)["targets"]
    for name, target in targets.items():
        target["id"] = name
        missing = [key for key in REQUIRED if key not in target]
        if missing:
            sys.exit("targets.toml: %s lacks %s" % (name, ", ".join(missing)))
        if target["component"] not in COMPONENTS:
            sys.exit("targets.toml: %s: component %r" % (name, target["component"]))
        if target["availability"] not in ("public", "retail"):
            sys.exit("targets.toml: %s: availability %r" % (name, target["availability"]))
    return targets


def simulators(targets=None, built=False):
    """The simulator's targets, in the manifest's order, or (built) the baseline, which defines no
    identity macro, and then the editions in the order they were built."""
    targets = targets or load()
    names = [name for name, t in targets.items() if t["component"] == "simulator"]
    if built:
        names.sort(key=lambda name: (bool(targets[name]["macros"]), targets[name]["linked"]))
    return names


def build_dir(target):
    """A target's CMake directory in the build tree, and the environment file of the nested build
    that holds it (another compiler's: vc22, vc40), if any."""
    where = target["built-in"] + "/" if target["built-in"] else ""
    return where + "CMakeFiles/%s.dir" % target["id"].lower(), (
        target["built-in"] + "-env.cmake" if target["compiler"] != "4.1" else None)


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def date(value):
    return str(value)


def output_path(target):
    return (target["built-in"] + "/" if target["built-in"] else "") + target["output"]


def status_table(targets):
    rows = [("`%s`" % t["binary"], t["what"], t["edition"], t["total"],
             "[report](%s/%sPROGRESS.HTML)" % (PAGES, name)) for name, t in targets.items()]
    return table(("Binary", "What it is", "Edition", "Game-code functions", "Progress"), rows)


def document(targets):
    out = ["# Targets", "",
           "<!-- Generated by tools/targets.py --doc from targets.toml. Don't edit: change targets.toml and rerun. -->",
           "",
           "Every binary the project rebuilds and compares with an original is a **target**, declared once, in",
           "[`targets.toml`](../targets.toml). This page is generated from that file. The simulator's editions,",
           "which share one source, are described in [EDITIONS.md](EDITIONS.md).", "",
           "## The targets", "",
           "In `targets.toml`'s order, which is also the order of a shared function's annotations.", "",
           table(("Target", "Binary", "Component", "Edition", "Compiler", "Sources"),
                 [("`%s`" % name, "`%s`" % t["binary"], t["component"], t["edition"], "VC++ " + t["compiler"],
                   ", ".join("`%s/`" % s for s in t["sources"])) for name, t in targets.items()]), ""]
    for name, t in targets.items():
        out += ["- **%s** (`%s`): %s" % (name, t["binary"], " ".join(t["about"].split()))]
    out += ["",
            "## The originals", "",
            "The project names each original after its target; the 3D-card editions' simulators and Ghost Bear's",
            "Legacy's are all `MW2.DLL` on their discs. A **public** original is freely downloadable, and CI",
            "fetches it; a **retail** one isn't, and CI compares it from a private repository. **Linked** is the",
            "day in the file's PE header, in UTC; a disc's file date is local time, and can be the day before.", "",
            table(("Binary", "Size", "SHA-256", "Linked", "Availability", "Where it comes from"),
                  [("`%s`" % t["binary"], "{:,} bytes".format(t["size"]), "`%s`" % t["sha256"], date(t["linked"]),
                    t["availability"], " ".join(t["origin"].split())) for t in targets.values()]), "",
            "## Build configuration", "",
            "Each target needs the compiler its original was built with ([BUILDING.md](BUILDING.md)). The",
            "binaries are written to the build tree's root or the subdirectory given.", "",
            table(("Target", "Compiler", "Language", "`cl` flags", "CRT", "Link", "Rebuilt as", "Identity macros"),
                  [("`%s`" % name, "VC++ " + t["compiler"], t["language"], t["cl"], t["crt"], t["link"],
                    "`%s`" % output_path(t), ", ".join("`%s`" % m for m in t["macros"]) or "none")
                   for name, t in targets.items()]), "",
            "## Game code", "",
            "Progress counts game code only: reccmp runs with `--nolib` and `--total`, the number of game-code",
            "functions in the original.", "",
            table(("Target", "`--total`", "The game code is everything"),
                  [("`%s`" % name, t["total"], " ".join(t["game-code"].split())) for name, t in targets.items()]),
            "",
            "## `reccmp-user.yml`", "",
            "To compare with your own copies of the originals, create `reccmp-user.yml` in the repository root",
            "with the targets you have:", "",
            "```yaml", "targets:"]
    for name, t in targets.items():
        out += ["  %s:" % name, "    path: path/to/%s" % t["binary"]]
    out += ["```", ""]
    return "\n".join(out)


def splice(text, name, body):
    begin, end = BEGIN % name, END % name
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        sys.exit("README.md: no %s ... %s markers" % (begin, end))
    return pattern.sub(lambda _: begin + "\n" + body + "\n" + end, text)


def readme(targets):
    return splice(README.read_text(encoding="utf-8"), "status", status_table(targets))


def check_reccmp_project(targets, problems):
    project = load_yaml(ROOT / "reccmp-project.yml")["targets"]
    if list(project) != list(targets):
        problems.append("reccmp-project.yml lists %s; targets.toml lists %s" % (" ".join(project), " ".join(targets)))
    for name in set(project) & set(targets):
        theirs, ours = project[name], targets[name]
        for what, a, b in (("filename", theirs.get("filename"), ours["binary"]),
                           ("sha256", theirs.get("hash", {}).get("sha256"), ours["sha256"]),
                           ("source-root", list(theirs.get("source-root", [])), list(ours["sources"]))):
            if a != b:
                problems.append("reccmp-project.yml: %s's %s is %s; targets.toml says %s" % (name, what, a, b))


def find(text, pattern, where, problems):
    match = re.search(pattern, text, re.M)
    if not match:
        problems.append("%s: no line matching %s (update tools/targets.py with the workflow)" % (where, pattern))
        return None
    return match.group(1)


def check_workflows(targets, problems):
    """verify-retail.yml keeps its list by hand (a workflow_run workflow, run from the base branch,
    whose env block can't be computed); build.yml asks this script (--list, --sources)."""
    retail = [n for n, t in targets.items() if t["availability"] == "retail"]

    verify = (ROOT / ".github/workflows/verify-retail.yml").read_text(encoding="utf-8")
    # Its entries may be in any order: the workflow runs the small targets first.
    found = find(verify, r'^\s*RETAIL_ENTRIES: "([^"]*)"', "verify-retail.yml", problems)
    wanted = ["%s:%s:%d" % (n, targets[n]["binary"], targets[n]["total"]) for n in retail]
    if found is not None and sorted(found.split()) != sorted(wanted):
        problems.append("verify-retail.yml: RETAIL_ENTRIES is \"%s\"; targets.toml gives \"%s\"" % (found, " ".join(wanted)))
    sums = dict((name, digest) for digest, name in re.findall(r"^\s*([0-9a-f]{64}) \*(\S+)$", verify, re.M))
    wanted = dict((targets[n]["binary"], targets[n]["sha256"]) for n in retail)
    if sums != wanted:
        for name in sorted(set(sums) | set(wanted)):
            if sums.get(name) != wanted.get(name):
                problems.append("verify-retail.yml: the hash of %s is %s; targets.toml says %s"
                                % (name, sums.get(name), wanted.get(name)))


def check(targets):
    problems = []
    if not DOC.exists() or DOC.read_text(encoding="utf-8") != document(targets):
        problems.append("docs/TARGETS.md is stale: run python tools/targets.py --doc")
    if README.read_text(encoding="utf-8") != readme(targets):
        problems.append("README.md's status table is stale: run python tools/targets.py --doc")
    check_reccmp_project(targets, problems)
    check_workflows(targets, problems)
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--doc", action="store_true", help="rewrite docs/TARGETS.md and the README's status table")
    group.add_argument("--check", action="store_true", help="fail when a document or a hand-kept list disagrees")
    group.add_argument("--list", action="store_true", help="print the targets")
    group.add_argument("--sources", metavar="TARGET", help="print a target's source directories")
    parser.add_argument("--availability", choices=["public", "retail"], help="--list: only these")
    parser.add_argument("--format", choices=["ids", "totals", "entries"], default="ids",
                        help="--list: the names, TARGET:TOTAL or TARGET:BINARY:TOTAL")
    args = parser.parse_args()
    targets = load()

    if args.list:
        for name, t in targets.items():
            if args.availability in (None, t["availability"]):
                print({"ids": name, "totals": "%s:%d" % (name, t["total"]),
                       "entries": "%s:%s:%d" % (name, t["binary"], t["total"])}[args.format])
    elif args.sources:
        if args.sources not in targets:
            sys.exit("no target %s in targets.toml" % args.sources)
        print(" ".join(targets[args.sources]["sources"]))
    elif args.doc:
        text = readme(targets)
        DOC.write_text(document(targets), encoding="utf-8")
        README.write_text(text, encoding="utf-8")
        print("wrote docs/TARGETS.md and README.md's status table")
    else:
        problems = check(targets)
        for problem in problems:
            print(problem)
        if problems:
            sys.exit(1)
        print("targets.toml, docs/TARGETS.md, README.md, reccmp-project.yml and verify-retail.yml agree (%d targets)"
              % len(targets))


if __name__ == "__main__":
    main()
